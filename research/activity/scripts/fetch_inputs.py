"""Download the large raw inputs that are NOT stored in research/activity/raw/ (>5 MB or licence/size reasons).

  python3 fetch_inputs.py [--raw DIR]     (needs curl, unzip; network access)

Small inputs (EIA MER tables, OWID grapher CSVs, IRENA tables, OWID minerals CSVs, UN SDMX extract, RDS-2, wells tables,
WNA table) are already in research/activity/raw/. To refresh them see README.md.
"""
import os,sys,subprocess,json
sys.path.insert(0,os.path.dirname(os.path.abspath(__file__)))
from lib import RAW
def sh(*a): print('+',' '.join(a),flush=True); subprocess.run(a,check=True)
os.makedirs(RAW+'fao/x',exist_ok=True)
# 1. OWID energy dataset (9 MB)
sh('curl','-sS','-L','-o',RAW+'owid-energy.csv','https://raw.githubusercontent.com/owid/energy-data/master/owid-energy-data.csv')
# 2. FAOSTAT Forestry bulk file (18 MB zip, 318 MB csv)
sh('curl','-sS','-L','-o',RAW+'fao/forestry.zip','https://bulks-faostat.fao.org/production/Forestry_E_All_Data_(Normalized).zip')
sh('unzip','-o','-q',RAW+'fao/forestry.zip','-d',RAW+'fao/x')
# 3. EIA International Energy Statistics bulk file (24 MB zip) -> eia_annual.json (81 MB)
sh('curl','-sS','-L','-o',RAW+'INTL.zip','https://www.eia.gov/opendata/bulk/INTL.zip')
sh('unzip','-o','-q',RAW+'INTL.zip','-d',RAW)
txt=[f for f in os.listdir(RAW) if f.upper().startswith('INTL') and f.endswith('.txt')][0]
sh(sys.executable,os.path.join(os.path.dirname(os.path.abspath(__file__)),'eia_extract.py'),RAW+txt,RAW+'eia_annual.json')
print('done; eta_us.json is regenerated by build_coal.py')
